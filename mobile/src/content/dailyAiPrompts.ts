/** Күнделікті AI сұрақ — басты беттен ImamAI-ға бір рет жіберіледі. */
export const DAILY_AI_PROMPTS_KK: readonly string[] = [
  "Бүгінгі намазымды қалай жақсарта аламын?",
  "Зекет беру туралы қысқаша түсіндірме беріңіз.",
  "Ораза ұстаудың негізгі шарттары қандай?",
  "Тәубе қалай дұрыс етіледі?",
  "Отбасылық сабыр туралы аят немесе хадис айтып беріңіз.",
  "Дұға оқудың этикеті қандай?",
  "Хадис пен Құран айырмашылығын қысқаша түсіндіріңіз.",
  "Исламда көршілердің құқығы қандай?",
  "Намазда қысқартылған жағдайлар қашан болады?",
  "Садақа мен зекет айырмашылығы неде?",
];

export function getDailyAiPrompt(now = new Date()): string {
  const day = Math.floor(now.getTime() / 86400000);
  return DAILY_AI_PROMPTS_KK[day % DAILY_AI_PROMPTS_KK.length]!;
}
