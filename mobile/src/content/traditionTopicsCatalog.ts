export function getTraditionTopics(): TraditionTopic[] {
  return TRADITION_TOPICS;
}

export function getTraditionTopicById(id: string): TraditionTopic | undefined {
  return TRADITION_TOPICS.find((topic) => topic.id === id);
}

export function getTraditionTopicByTitle(title: string): TraditionTopic | undefined {
  return TRADITION_TOPICS.find((topic) => topic.title === title);
}

export function getTraditionAudioById(id: string): TraditionAudioBlessing | undefined {
  const resolved = resolveBlessingId(id);
  return TRADITION_AUDIO_BLESSINGS.find((audio) => audio.id === resolved);
}

export function getTraditionArticleById(id: string): TraditionArticle | undefined {
  return TRADITION_ARTICLES.find((article) => article.id === id);
}

export function getRelatedTraditionAudios(topicId: string, query = ""): TraditionAudioBlessing[] {
  if (topicId === "bata-beru") {
    return query.trim() ? searchTraditionBatas(query) : getAllTraditionBatas();
  }
  const topic = getTraditionTopicById(topicId);
  const ids = topic?.audioIds ?? [];
  if (ids.length) {
    const byId = new Map(TRADITION_AUDIO_BLESSINGS.map((audio) => [audio.id, audio]));
    return ids
      .map((id) => byId.get(resolveBlessingId(id)))
      .filter((audio): audio is TraditionAudioBlessing => Boolean(audio));
  }
  return TRADITION_AUDIO_BLESSINGS.filter((audio) => audio.topicId === topicId);
}

export function getRelatedTraditionArticles(topicId: string): TraditionArticle[] {
  const topic = getTraditionTopicById(topicId);
  const ids = topic?.articleIds ?? [];
  if (ids.length) {
    const byId = new Map(TRADITION_ARTICLES.map((article) => [article.id, article]));
    return ids.map((id) => byId.get(id)).filter((article): article is TraditionArticle => Boolean(article));
  }
  return TRADITION_ARTICLES.filter((article) => article.topicId === topicId || article.id === "tradition-values");
}

export function traditionCategoryLabel(category: TraditionTopicCategory): string {
  switch (category) {
    case "family":
      return "Отбасы";
    case "social":
      return "Қоғам";
    case "ceremony":
      return "Рәсім";
    case "faith":
      return "Дінмен байланыс";
    default:
      return category;
  }
}

export function traditionTopicSearchBlob(topic: TraditionTopic): string {
  const evidenceText = getTraditionReligiousEvidence(topic.id)
    .flatMap((b) => [b.titleKk, b.noteKk ?? "", ...b.refs.map((r) => `${r.citationKk} ${r.excerptKk}`)])
    .join(" ");
  return [
    topic.title,
    topic.subtitle,
    topic.summary,
    topic.origin,
    topic.religionLink,
    topic.howTo.join(" "),
    topic.categories.map(traditionCategoryLabel).join(" "),
    evidenceText,
  ]
    .join(" ")
    .toLowerCase();
}
