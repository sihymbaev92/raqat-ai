/** Салт-дәстүр тақырыптарына аят/хадис сілтемелері — «Дінмен ұштасуы» вкладкасы. */

export type TraditionQuranRef = {
  kind: "quran";
  surah: number;
  ayah: number;
  ayahEnd?: number;
  citationKk: string;
  excerptKk: string;
};

export type TraditionHadithRef = {
  kind: "hadith";
  citationKk: string;
  excerptKk: string;
  /** Корпуста болса — хадис экранына өту */
  hadithId?: string;
};

export type TraditionEvidenceRef = TraditionQuranRef | TraditionHadithRef;

export type TraditionEvidenceBlock = {
  id: string;
  titleKk: string;
  noteKk?: string;
  refs: TraditionEvidenceRef[];
};

const q = (
  surah: number,
  ayah: number,
  citationKk: string,
  excerptKk: string,
  ayahEnd?: number
): TraditionQuranRef => ({
  kind: "quran",
  surah,
  ayah,
  ayahEnd,
  citationKk,
  excerptKk,
});

const h = (citationKk: string, excerptKk: string, hadithId?: string): TraditionHadithRef => ({
  kind: "hadith",
  citationKk,
  excerptKk,
  hadithId,
});

