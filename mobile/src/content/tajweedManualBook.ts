type LetterLessonInput = Omit<
  Extract<TajweedManualBookBlock, { type: "letterLesson" }>,
  "type" | "examplesCaption"
> & {
  examplesCaption?: string;
};

function letterLesson(input: LetterLessonInput): TajweedManualBookBlock {
  return {
    type: "letterLesson",
    examplesCaption: "Арабша мысалдар және транскрипция",
    ...input,
  };
}

function alphabetPage(page: number, blocks: TajweedManualBookBlock[]): TajweedManualBookPage {
  return { page, quality: "manual", blocks };
}

