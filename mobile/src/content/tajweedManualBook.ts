function ex(arabic: string, reading?: string, label?: string): TajweedManualBookExample {
  return { arabic, reading, label };
}

function manualPage(
  page: number,
  title: string,
  paragraphs: string[],
  examples: TajweedManualBookExample[] = [],
  exercises: string[] = [],
  notes: string[] = []
): TajweedManualBookPage {
  return {
    page,
    quality: "manual",
    blocks: [
      { type: "chapterTitle", text: title },
      ...paragraphs.map((text): TajweedManualBookBlock => ({ type: "paragraph", text })),
      ...(examples.length ? [{ type: "examples" as const, items: examples }] : []),
      ...exercises.map((text): TajweedManualBookBlock => ({ type: "exercise", text })),
      ...notes.map((text): TajweedManualBookBlock => ({ type: "note", text })),
    ],
  };
}

