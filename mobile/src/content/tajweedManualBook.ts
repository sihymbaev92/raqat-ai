export type TajweedManualBookExample = {
  arabic?: string;
  reading?: string;
  label?: string;
};

export type TajweedManualCropRect = { x: number; y: number; width: number; height: number };

export type TajweedManualBookBlock =
  | { type: "partTitle"; text: string }
  | { type: "chapterTitle"; text: string; subtitle?: string }
  | { type: "paragraph"; text: string }
  | { type: "rule"; title: string; mark?: string; text: string }
  | {
      type: "imageCrop";
      sourcePage: number;
      caption: string;
      rect: TajweedManualCropRect;
    }
  | {
      type: "letterLesson";
      title: string;
      text: string;
      sourcePage: number;
      mouthCaption: string;
      mouthRect: TajweedManualCropRect;
      examplesCaption: string;
      examplesRect: TajweedManualCropRect;
      examples?: TajweedManualBookExample[];
    }
  | { type: "examples"; items: TajweedManualBookExample[] }
  | { type: "exercise"; text: string }
  | { type: "note"; text: string };

export type TajweedManualBookPage = {
  page: number;
  blocks: TajweedManualBookBlock[];
  quality: "manual" | "text-source";
};

