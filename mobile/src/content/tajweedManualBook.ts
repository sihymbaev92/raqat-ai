export function getTajweedManualBookPage(page: number): TajweedManualBookPage | undefined {
  const manual = MANUAL_PAGES[page];
  if (manual) return manual;

  const source = getMuftyatPageText(page);
  if (!source?.displayText.trim()) return undefined;

  return {
    page,
    quality: "text-source",
    blocks: displayTextToBlocks(source.displayText),
  };
}

function displayTextToBlocks(displayText: string): TajweedManualBookBlock[] {
  const lines = displayText
    .split("\n")
    .map((line) => normalizeLine(line))
    .filter((line, index) => line.length > 0 && !(index === 0 && /^\d+$/.test(line)));

  const blocks: TajweedManualBookBlock[] = [];
  let paragraphParts: string[] = [];
  let exampleItems: TajweedManualBookExample[] = [];
  let collectingExamples = false;

  const flushParagraph = () => {
    const text = joinParagraphParts(paragraphParts);
    paragraphParts = [];
    if (text) blocks.push({ type: "paragraph", text });
  };

  const flushExamples = () => {
    if (exampleItems.length > 0) {
      blocks.push({ type: "examples", items: exampleItems });
    }
    exampleItems = [];
    collectingExamples = false;
  };

  for (const line of lines) {
    if (isLayoutNoiseLine(line)) {
      continue;
    }

    if (isExampleHeading(line)) {
      flushParagraph();
      flushExamples();
      collectingExamples = true;
      continue;
    }

    const standalone = standaloneBlockForLine(line);
    if (standalone) {
      flushParagraph();
      flushExamples();
      blocks.push(standalone);
      continue;
    }

    if (collectingExamples) {
      if (isExampleReadingLine(line)) {
        exampleItems.push({ reading: line });
        continue;
      }
      flushExamples();
    }

    appendParagraphPart(paragraphParts, line);
    if (shouldCloseParagraph(line)) {
      flushParagraph();
    }
  }

  flushParagraph();
  flushExamples();
  return blocks;
}

function normalizeLine(line: string): string {
  return line.replace(/\s+/g, " ").trim();
}

function standaloneBlockForLine(line: string): TajweedManualBookBlock | null {
  if (/^Жаттығу[:.]?/.test(line)) {
    return { type: "exercise", text: line };
  }
  if (/^Ескерту[:.]?/.test(line)) {
    return { type: "note", text: line };
  }
  if (/^\d+\s*[–-]\s*бөлім$/i.test(line) || /^\d+\.\s*бөлім$/i.test(line)) {
    return { type: "partTitle", text: line.toUpperCase() };
  }
  if (/^\d+\.\s+/.test(line) || /^[А-ЯӘІҢҒҮҰҚӨҺ\s–-]+$/.test(line) || isShortTopicTitle(line)) {
    return { type: "chapterTitle", text: line };
  }
  if (/^[٭•♦]\s*/.test(line)) {
    const text = line.replace(/^[٭•♦]\s*/, "");
    return { type: "rule", title: text, text: "" };
  }
  return null;
}

function appendParagraphPart(parts: string[], line: string): void {
  if (parts.length === 0) {
    parts.push(line);
    return;
  }

  const last = parts[parts.length - 1];
  if (last.endsWith("-")) {
    parts[parts.length - 1] = `${last.slice(0, -1)}${line}`;
    return;
  }

  parts.push(line);
}

function joinParagraphParts(parts: string[]): string {
  return parts
    .join(" ")
    .replace(/\s+([,.;:!?])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

function shouldCloseParagraph(line: string): boolean {
  if (line.endsWith("-")) return false;
  return /[.!?;:»)]$/.test(line);
}

function isExampleHeading(line: string): boolean {
  return /^Мысалы[:.]?$/.test(line);
}

function isExampleReadingLine(line: string): boolean {
  if (isLayoutNoiseLine(line)) return false;
  if (standaloneBlockForLine(line)) return false;
  if (line.length > 42) return false;
  if (/[.!?;:]$/.test(line)) return false;
  return true;
}

function isLayoutNoiseLine(line: string): boolean {
  const lower = line.toLowerCase();
  if (TABLE_NOISE_LINES.has(lower)) return true;
  if (/^\d+$/.test(line)) return true;
  if (/^[а-яәіңғүұқөһ‘' ,]+$/i.test(line) && line.includes(",") && line.length <= 32) {
    return true;
  }
  return false;
}

function isShortTopicTitle(line: string): boolean {
  if (line.length > 42) return false;
  return SHORT_TOPIC_TITLES.has(line.toLowerCase());
}

