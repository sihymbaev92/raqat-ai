export function tajweedSectionDisplayTitle(
  titleKk: string,
  locale: AppLocale,
  tr: (text: string) => string
): string {
  const key = (titleKk ?? "").trim();
  if (!key || locale === "kk") return titleKk;
  if (locale === "ru" && TAJWEED_SECTION_TITLE_RU[key]) return TAJWEED_SECTION_TITLE_RU[key]!;
  const translated = tr(key);
  if (translated && translated !== "…") return translated;
  return TAJWEED_SECTION_TITLE_RU[key] ?? "…";
}
