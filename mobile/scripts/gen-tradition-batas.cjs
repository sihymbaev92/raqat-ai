let n = 0;
const items = [];
for (const cat of categories) {
  for (const [title, text] of cat.titles) {
    n += 1;
    items.push({
      id: `bata-${String(n).padStart(3, "0")}`,
      category: cat.key,
      categoryLabel: cat.label,
      topicId: cat.topicId,
      title,
      text,
      sourceLabel: `${cat.label} батасы`,
    });
  }
}

