#!/usr/bin/env node
/** dhikr-list.json: қазақша мағына/атау грамматикасын түзету. */
const fs = require("fs");
const path = require("path");

const FIELDS = ["textKk", "meaningKk"];

const REPLACEMENTS = [
  [/тәспі/g, "тәспих"],
  [/Аллаһты мадақтай отырып, Оны бар кемшіліктен пәк деп айту\./g, "Аллаһты мадақтап, Оны бар кемшіліктен пәк деп айту."],
  [/Аллаһты мадақтай пәк айтамын, кешірім сұраймын\./g, "Аллаһты мадақтап, пәк айтамын; кешірім сұраймын."],
  [/Оңайлық пен күш тек Аллаһта\./g, "Қуат пен күш тек Аллаһта."],
  [/ең жақсы сенімді қорғаушы/g, "ең жақсы уәкіл"],
  [/Аллаһты Раббым, Исламды дінім деп қанағаттандым\./g, "Аллаһты Раббым, Исламды дінім деп қанағаттанамын."],
  [/салаamat/g, "салаамат"],
  [/Пайғамбарға салауат\./g, "Пайғамбарға сәләуәт."],
  [/бастапқысы\)/g, "бастауы)"],
  [/бастапқы ескерту\)/g, "аяттың бастауы)"],
  [/сүре бастапқысы\)/g, "сүре бастауы)"],
  [/Фалақ бастапқысы\)/g, "«Әл-Фалақ» сүресінің бастауы)"],
  [/Нас бастапқысы\)/g, "«Ән-Нас» сүресінің бастауы)"],
  [/қысқа куәлік\)/g, "қысқа куәлігі)"],
  [/Бергеніңді тыймайтын жоқ\./g, "Сен бергенді ешкім тоқтата алмайды."],
  [/Раббым, кеудемді жайғасын/g, "Раббым, кеудемді жайластыр"],
  [/Сен Саламсың, салаамат Сенен/g, "Сен — Сәләм Өзісің, сәләм Сенен"],
  [/Тірі, өзінен тұратын \(дуаға жиі қосылады\)\./g, "Тірі, Тұрағы өзінде болушы (дуаға жиі қосылады)."],
  [/Раббым ең биік — пәк \(жалпы зікір ретінде\)\./g, "Раббым — ең биік, Ол пәк (жалпы зікір ретінде)."],
  [/Раббым ұлы — пәк \(жалпы зікір\)\./g, "Раббым — ұлы, Ол пәк (жалпы зікір)."],
  [
    /Намаздан кейінгі тәспих: алдымен «СубханаЛлаһ» 33 рет, содан «Әлхамдулиллаһ» 33 рет, соңғысы «Аллаһу акбар» 33 рет — барлығы 99\./g,
    "Намаздан кейінгі тәспих: алдымен «СубханаЛлаһ» 33 рет, кейін «Әлхамдулиллаһ» 33 рет, соңында «Аллаһу акбар» 33 рет — барлығы 99.",
  ],
  [/абwаба/g, "әбуаба"],
  [/\(есім\)/g, "(аят үзіндісі)"],
];

function applyFixes(raw) {
  let out = raw;
  for (const [re, rep] of REPLACEMENTS) {
    out = out.replace(re, rep);
  }
  return out;
}

const jsonPath = path.join(__dirname, "../assets/bundled/dhikr-list.json");
const data = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
let changed = 0;

for (const item of data.items ?? []) {
  for (const field of FIELDS) {
    if (typeof item[field] !== "string") continue;
    const next = applyFixes(item[field]);
    if (next !== item[field]) {
      item[field] = next;
      changed += 1;
    }
  }
}

fs.writeFileSync(jsonPath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
console.log(`dhikr-list.json: fixed ${changed} text fields`);
