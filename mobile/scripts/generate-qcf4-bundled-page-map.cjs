#!/usr/bin/env node
/** Generates QCF4 page loader — full bundled map (dev) or CDN-only stub (release APK). */
const fs = require("fs");
const path = require("path");

const mobile = path.join(__dirname, "..");
const pagesDir = path.join(mobile, "assets", "quran", "qcf4", "pages");
const out = path.join(mobile, "src", "quran", "qcf4BundledPageAssets.generated.ts");
const cdnOnly =
  process.argv.includes("--cdn-only") || process.env.RAQAT_QCF4_CDN_ONLY === "1";

function writeCdnOnlyStub() {
  const body = `/** Auto-generated by scripts/generate-qcf4-bundled-page-map.cjs --cdn-only — do not edit. */
import type { Qcf4PageJson } from "./qcf4Types";

/** Release APK: 604 бет JSON Metro bundle-ға кірмейді — CDN + FileSystem cache. */
export function loadQcf4BundledPageJson(_page: number): Qcf4PageJson | null {
  return null;
}
`;
  fs.writeFileSync(out, body, "utf8");
  console.log(`wrote ${out} (CDN-only stub)`);
}

if (cdnOnly) {
  writeCdnOnlyStub();
  process.exit(0);
}

if (!fs.existsSync(pagesDir)) {
  console.warn(`pages dir missing (${pagesDir}) — writing CDN-only stub`);
  writeCdnOnlyStub();
  process.exit(0);
}

const files = fs
  .readdirSync(pagesDir)
  .filter((f) => /^\d{3}\.json$/.test(f))
  .sort();

const cases = files
  .map((f) => {
    const page = parseInt(f.slice(0, 3), 10);
    return `    case ${page}:\n      return require("../../assets/quran/qcf4/pages/${f}") as Qcf4PageJson;`;
  })
  .join("\n");

const body = `/** Auto-generated by scripts/generate-qcf4-bundled-page-map.cjs — do not edit. */
import type { Qcf4PageJson } from "./qcf4Types";

export function loadQcf4BundledPageJson(page: number): Qcf4PageJson | null {
  switch (page) {
${cases}
    default:
      return null;
  }
}
`;

fs.writeFileSync(out, body, "utf8");
console.log(`wrote ${out} (${files.length} pages)`);
