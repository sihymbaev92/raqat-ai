def fetch_ar(con: sqlite3.Connection, collection: str, no: int) -> tuple[str, str, str]:
    source = "Sahih al-Bukhari" if collection == "bukhari" else "Sahih Muslim"
    row = con.execute(
        """
        SELECT text_ar, coalesce(book_name,''), coalesce(chapter,''), coalesce(grade,'')
        FROM hadith
        WHERE source=? AND cast(hadith_no as text)=?
        ORDER BY id
        LIMIT 1
        """,
        (source, str(no)),
    ).fetchone()
    if not row:
        row = con.execute(
            """
            SELECT text_ar, coalesce(book_name,''), coalesce(chapter,''), coalesce(grade,'')
            FROM hadith
            WHERE source=? AND reference LIKE ?
            ORDER BY id
            LIMIT 1
            """,
            (source, f"%{no}%"),
        ).fetchone()
    if not row:
        return "", "", ""
    return (row[0] or "").strip(), (row[1] or "").strip(), (row[3] or "").strip() or "сахих"


