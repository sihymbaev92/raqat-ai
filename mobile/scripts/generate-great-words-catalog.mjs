function quoteForAuthor(authorId, seq) {
  const list = AUTHOR_QUOTES[authorId];
  if (list?.length) {
    const q = list[seq % list.length];
    return { text: q.text, label: "Сөз", title: q.title, source: null };
  }
  const pr = PROVERB_SEEDS[seq % PROVERB_SEEDS.length];
  const folkLabel =
    authorId === "sheshei" ? "Шешейдің өсиеті" : authorId === "mystic" ? "Рухани нақыл" : "Халық нақылы";
  return { text: pr, label: folkLabel, title: null, source: null };
}

function buildBody(i, quote) {
  const a = P1[i % P1.length];
  const b = P2[(i * 3) % P2.length];
  const c = P3[(i * 5) % P3.length];
  const dPool = quote.label === "Қара сөз" ? P4_ABAI : P4_GENERIC;
  const d = dPool[(i * 7) % dPool.length];
  const head = quote.source ? `${quote.label} (${quote.source})` : quote.label;
  return (
    `${a}\n\n${b}\n\n${head}:\n«${quote.text}»\n\n${c}\n\n${d}\n\n` +
    `${quote.label} (түпкілігі):\n«${quote.text}»`
  );
}

function titleForQuote(quote) {
  if (quote.title) return quote.title;
  const t = quote.text.trim();
  return t.length > 52 ? `${t.slice(0, 49)}…` : t;
}

function buildAbaiKaraSozEntries() {
  if (!fs.existsSync(ABAI_KARA_SOZ_JSON)) {
    throw new Error(
      `Жоқ: ${ABAI_KARA_SOZ_JSON}. Алдымен: node mobile/scripts/parse-abai-kara-soz.mjs`
    );
  }
  const { items } = JSON.parse(fs.readFileSync(ABAI_KARA_SOZ_JSON, "utf8"));
  return items.map((ks) => {
    const yearNote = ks.years?.length ? ` · ${ks.years.join(", ")}` : "";
    const head = `Абай Құнанбаев. «Қара сөз», ${ks.number}-ші сөз${yearNote}`;
    return {
      id: `abai-ks-${String(ks.number).padStart(2, "0")}`,
      authorId: "abai",
      title: ks.title,
      body: `${head}\n\n${ks.text}`,
      karaSozNumber: ks.number,
    };
  });
}

const ROTATION_AUTHORS = AUTHORS.filter((a) => a.id !== "abai");
const authorSeq = Object.fromEntries(ROTATION_AUTHORS.map((a) => [a.id, 0]));

const abaiEntries = buildAbaiKaraSozEntries();
const COUNT = 1200;
const entries = [...abaiEntries];
for (let i = 0; i < COUNT; i++) {
  const author = ROTATION_AUTHORS[i % ROTATION_AUTHORS.length];
  const seq = authorSeq[author.id]++;
  const quote = quoteForAuthor(author.id, seq);
  const id = `gw-${String(entries.length + 1).padStart(4, "0")}`;
  entries.push({
    id,
    authorId: author.id,
    title: titleForQuote(quote),
    body: buildBody(i, quote),
    proverbKey: String(seq % PROVERB_SEEDS.length),
  });
}

